#ifndef SORTING_HPP
#define SORTING_HPP

#include <vector>

// Все три функции упорядочивают numbers по неубыванию: {3, -1, 2, -1} → {-1, -1, 2, 3}.

/// Сортировка пузырьком: просмотр справа налево, меньший из двух соседних элементов
/// перемещается влево; после i-го просмотра на месте i стоит i-й по величине элемент.
void bubbleSort(std::vector<int>& numbers);

/// Шейкерная сортировка: пузырьковая с чередованием направлений просмотра; просмотр
/// ограничивается местом последнего обмена, сортировка заканчивается, когда обменов нет.
void shakerSort(std::vector<int>& numbers);

/// Сортировка выбором: наименьший элемент оставшейся части меняется местами с её первым элементом.
void selectionSort(std::vector<int>& numbers);

#endif // SORTING_HPP
